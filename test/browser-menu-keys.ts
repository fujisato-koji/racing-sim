// メニューをキーボードだけで進める確認：タイトルで Enter、コースで ←→ と ↑↓、Enter で車、↑↓ で車を変え、Esc で戻り、もう一度進んでレースを始める。
// 途中の画面を撮る。先に `npx vite preview --port 4173` を起動しておく。実行: npx tsx test/browser-menu-keys.ts <出力先>
import { chromium } from 'playwright-core';
const out = process.argv[2] ?? '.';
const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors: string[] = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto('http://localhost:4173/?debug');
await page.waitForSelector('[data-go]', { timeout: 60000 });
await page.waitForTimeout(2500);
let fail = 0;
const check = (ok: boolean, msg: string) => { console.log(`${ok ? 'OK  ' : 'NG  '} ${msg}`); if (!ok) fail++; };
const course = () => page.evaluate('window.__app.course.id') as Promise<string>;
const car = () => page.evaluate('window.__app.car.id') as Promise<string>;
const title = () => page.evaluate(`document.querySelector('.screen-title')?.textContent ?? ''`) as Promise<string>;

await page.keyboard.press('Enter');
await page.waitForTimeout(800);
check((await title()).includes('Choose a track'), 'タイトルで Enter → コースの画面');
await page.keyboard.press('ArrowRight');
await page.waitForTimeout(300);
const tab = await page.evaluate(`document.querySelector('.tab.selected')?.dataset.tab`);
check(tab === 'international', `→ で次の種類（${tab}）`);
await page.keyboard.press('ArrowDown');
await page.waitForTimeout(300);
const c1 = await course();
await page.keyboard.press('ArrowDown');
await page.waitForTimeout(300);
const c2 = await course();
check(c1 === 'suzuka' && c2 === 'spa', `↓ で一覧の上から選ぶ（${c1} → ${c2}）`);
await page.waitForTimeout(5000);
await page.screenshot({ path: `${out}/m1-course.png` });
await page.keyboard.press('Enter');
await page.waitForTimeout(1200);
check((await title()).includes('Choose a car'), 'Enter → 車の画面');
const k0 = await car();
await page.keyboard.press('ArrowDown');
await page.waitForTimeout(400);
const k1 = await car();
check(k0 !== k1, `↓ で車を変える（${k0} → ${k1}）`);
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/m2-car.png` });
await page.keyboard.press('Escape');
await page.waitForTimeout(800);
check((await title()).includes('Choose a track'), 'Esc → コースの画面に戻る');
check((await course()) === 'spa', '戻ってもコースの選択は残る');
await page.keyboard.press('Enter');
await page.waitForTimeout(800);
await page.keyboard.press('Enter');
await page.waitForSelector('.hud', { state: 'visible', timeout: 90000 });
check(true, '車の画面で Enter → レースが始まる');
await page.waitForTimeout(1500);
await page.keyboard.press('Escape');
await page.waitForTimeout(600);
await page.keyboard.press('ArrowDown');
await page.keyboard.press('ArrowDown');
await page.waitForTimeout(300);
const focused = await page.evaluate(`document.querySelector('.kb-focus')?.textContent ?? ''`) as string;
check(focused.includes('Restart'), `一時停止で ↓↓ → ボタンに印（${focused}）`);
await page.screenshot({ path: `${out}/m3-pause.png` });
console.log(errors.length ? errors.join('\n') : 'エラーなし');
console.log(fail === 0 ? 'すべて通過' : `${fail} 件の失敗`);
await browser.close();
process.exit(fail === 0 ? 0 : 1);
